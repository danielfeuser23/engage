def runtime_hashes():
 return {path.relative_to(ROOT/args.variant).as_posix():hashlib.sha256(path.read_bytes()).hexdigest()
         for path in (ROOT/args.variant).rglob('*')
         if path.is_file() and (path.suffix in ['.js','.css','.html']
          or 'assets' in path.relative_to(ROOT/args.variant).parts)}

def read_state(frame):
 # Read the LMS simulator's canonical data. Never inject or edit game state.
 return json.loads(frame.evaluate('parent.__data["cmi.suspend_data"]'))

def predictor_source():
 source=(ROOT/args.variant/'js/game.js').read_text()
 start=source.index('  function norm(s){')
 end=source.index('  function currentArea(){',start)
 fragment=source[start:end]
 # All copied functions execute against a NEW LOCAL S, not the live closure.
 # The game seed is generated by the ordinary character-creation UI and read only.
 script='''(seed)=>{
  const S={seed:seed,b:0,q:0};
  const D=window.GAME_DATA, MD=window.MONSTER_DATA;
 '''+fragment+'''
  const rows=[];
  for(let b=0;b<D.blocks.length;b++){
   for(let q=0;q<D.blocks[b].questions.length;q++){
    S.b=b;S.q=q;
    const enemy=encounter();
    rows.push({number:b*45+q+1,chapter:b+1,question:q+1,
     id:enemy.id,name:enemy.name,sprite:enemy.sprite,
     boss:!!enemy.boss,rare:!!enemy.rare});
   }
  }
  return rows;
 }'''
 return script,hashlib.sha256(fragment.encode()).hexdigest()

def read_enemy(frame):
 # Reduced motion may replace GIF src with a frozen data URL; motionSource
 # retains the original local filename and is also read only here.
 image=frame.locator('#enemyActor img.enemySprite')
 image.wait_for(state='visible')
 frame.wait_for_function('''()=>{
  const image=document.querySelector('#enemyActor img.enemySprite');
  return image&&image.complete&&image.naturalWidth>0;
 }''')
 source=image.evaluate('(img)=>img.dataset.motionSource||img.getAttribute("src")')
 assert source and not source.startswith('data:'),source
 return {
  'id':Path(urlsplit(source).path).stem,
  'sprite':source,
  'name':frame.locator('.enemyHud strong').inner_text(),
  'boss':frame.locator('#enemyActor.big').count()==1,
  'rare':frame.locator('.questionMeta .rare').count()==1,
 }

